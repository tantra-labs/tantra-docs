#!/usr/bin/env python3
"""Generate ``docs/api/api-reference.md`` from the runtime's checked-in OpenAPI document.

The source of truth is ``tantra-runtime/crates/tantra-runtime-api-rest/schema/openapi.v2.json``
(root design 0006 principle 5: docs are generated from ``openapi.v2.json``, never hand-listed).

    python3 scripts/gen_api_reference.py           # rewrite the page
    python3 scripts/gen_api_reference.py --check   # exit 1 when the page is stale (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

DOCS_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SPEC = (
    DOCS_ROOT.parent
    / "tantra-runtime"
    / "crates"
    / "tantra-runtime-api-rest"
    / "schema"
    / "openapi.v2.json"
)
OUTPUT = DOCS_ROOT / "docs" / "api" / "api-reference.md"
METHODS = ("get", "post", "put", "patch", "delete")


def _schema_name(schema: Any) -> str:
    if not isinstance(schema, dict):
        return "—"
    ref = schema.get("$ref")
    if isinstance(ref, str):
        return f"`{ref.rsplit('/', 1)[-1]}`"
    if schema.get("type") == "array":
        return f"array of {_schema_name(schema.get('items'))}"
    title = schema.get("title")
    if isinstance(title, str) and title != "AnyValue":
        return f"`{title}`"
    return "JSON"


def _body_schema(container: Any) -> str:
    if not isinstance(container, dict):
        return "—"
    content = container.get("content") or {}
    media = content.get("application/json") or {}
    return _schema_name(media.get("schema"))


def _scope(op: dict[str, Any]) -> str:
    security = op.get("security") or []
    scopes = sorted({s for req in security for v in req.values() for s in v})
    if not security:
        return "public"
    return ", ".join(scopes) if scopes else "any token"


def _params(op: dict[str, Any]) -> str:
    out = []
    for p in op.get("parameters") or []:
        if not isinstance(p, dict) or p.get("in") != "query":
            continue
        name = p.get("name", "?")
        out.append(f"`{name}`" + ("" if p.get("required") else "?"))
    return ", ".join(out) if out else "—"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def render(spec: dict[str, Any], spec_label: str) -> str:
    info = spec.get("info", {})
    server = (spec.get("servers") or [{}])[0].get("url", "/api/v2")
    tag_desc = {t["name"]: t.get("description", "") for t in spec.get("tags", [])}
    groups: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path in sorted(spec.get("paths", {})):
        ops = spec["paths"][path] or {}
        for method in METHODS:
            op = ops.get(method)
            if not isinstance(op, dict):
                continue
            tag = (op.get("tags") or ["other"])[0]
            groups.setdefault(tag, []).append((method.upper(), path, op))

    lines = [
        f"# {info.get('title', 'Tantra REST API')}",
        "",
        "<!-- Generated by tantra-docs/scripts/gen_api_reference.py from "
        f"{spec_label}. DO NOT EDIT: rerun the script. -->",
        "",
        f"- API version: `{info.get('version', '?')}`",
        f"- Base path: `{server}` (every path below is relative to it; there is no other prefix)",
        "- Every response is a `ResponseEnvelope` "
        "`{api_version, schema_version, data, error, meta}`; errors carry an `ErrorCode` whose "
        "HTTP status is fixed (validation 422, auth 401/403, not found 404, conflict 409, "
        "rate 429, unavailable 503).",
        "- **Scope** is the bearer-token scope required when auth is enabled "
        "(`public` = no token).",
        "- Machine-readable document: `GET /api/v2/openapi.json`; interactive UI: `/docs`.",
        "",
    ]
    for tag in sorted(groups):
        lines += [f"## {tag}", ""]
        if tag_desc.get(tag):
            lines += [tag_desc[tag], ""]
        lines += [
            "| Method | Path | Scope | Summary | Query | Request | Response |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for method, path, op in groups[tag]:
            ok = next(
                (v for k, v in (op.get("responses") or {}).items() if k.startswith("2")),
                None,
            )
            cap = op.get("x-tantra-max-body-bytes")
            request = _body_schema(op.get("requestBody"))
            if isinstance(cap, int) and op.get("requestBody"):
                request += f" (≤ {cap // 1024} KiB)"
            lines.append(
                "| `{m}` | `{p}` | {s} | {sum} | {q} | {req} | {resp} |".format(
                    m=method,
                    p=path,
                    s=_scope(op),
                    sum=_cell(op.get("summary", "")),
                    q=_params(op),
                    req=request,
                    resp=_body_schema(ok),
                )
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    ap.add_argument("--check", action="store_true", help="fail when the page is stale")
    args = ap.parse_args()
    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    label = "`tantra-runtime/crates/tantra-runtime-api-rest/schema/openapi.v2.json`"
    text = render(spec, label)
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"{OUTPUT.relative_to(DOCS_ROOT)} is stale; run scripts/gen_api_reference.py",
                file=sys.stderr,
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(DOCS_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
